use crate::{
    config::{License, ProjectOptions, SECTION_IDS},
    model::{validate_request, AppError, CreateRequest, Readme},
};
use serde::{Deserialize, Serialize};
use std::collections::HashSet;

#[derive(Clone, Deserialize, Serialize)]
pub struct IgnorePreset {
    pub id: String,
    pub name: String,
    pub group: String,
    pub patterns: Vec<String>,
}
pub fn ignore_catalog() -> Vec<IgnorePreset> {
    serde_json::from_str(include_str!("../resources/ignore-presets.json"))
        .expect("Bundled ignore catalog is valid")
}

pub fn render_gitignore(options: &ProjectOptions) -> Option<String> {
    let mut blocks = Vec::new();
    let mut seen = HashSet::new();
    // Positive duplicates are redundant only while no negation has intervened.
    // Reset at every negation, retaining both its position and later re-ignores.
    let mut add = |lines: &[String]| -> Vec<String> {
        lines
            .iter()
            .filter_map(|line| {
                if line.starts_with('!') {
                    seen.clear();
                    return Some(line.clone());
                }
                if seen.insert(line.clone()) {
                    Some(line.clone())
                } else {
                    None
                }
            })
            .collect()
    };
    for preset in ignore_catalog() {
        if options.ignore_presets.contains(&preset.id) {
            let lines = add(&preset.patterns);
            if !lines.is_empty() {
                blocks.push(format!("# {}\n{}", preset.name, lines.join("\n")));
            }
        }
    }
    if !options.custom_patterns.is_empty() {
        let lines = add(&options.custom_patterns);
        if !lines.is_empty() {
            blocks.push(format!(
                "# Custom patterns (applied last)\n{}",
                lines.join("\n")
            ));
        }
    }
    if blocks.is_empty() {
        return None;
    }
    Some(format!("# Generated by Repo Creator\n# Presets adapted from https://github.com/github/gitignore\n\n{}\n", blocks.join("\n\n")))
}

pub fn render_readme(request: &CreateRequest) -> Option<String> {
    if request.readme == Readme::None {
        return None;
    }
    let mut blocks = vec![format!("# {}", request.name)];
    if request.readme == Readme::Minimal {
        if !request.description.trim().is_empty() {
            blocks.push(request.description.trim().to_string());
        }
    } else {
        for id in SECTION_IDS {
            if !request.options.readme_sections.iter().any(|s| s == id) {
                continue;
            }
            let custom = request
                .options
                .section_content
                .get(*id)
                .map(|s| s.trim())
                .filter(|s| !s.is_empty());
            let (title, body) = match *id {
                "overview" => (
                    "Overview",
                    custom.unwrap_or(request.description.trim()).to_string(),
                ),
                "features" => (
                    "Features",
                    custom
                        .unwrap_or("<!-- List the project's implemented features. -->")
                        .to_string(),
                ),
                "installation" => (
                    "Installation",
                    custom
                        .unwrap_or("<!-- Add the prerequisites and actual installation steps. -->")
                        .to_string(),
                ),
                "usage" => (
                    "Usage",
                    custom
                        .unwrap_or("<!-- Add a short usage example. -->")
                        .to_string(),
                ),
                "development" => (
                    "Development",
                    custom
                        .unwrap_or(
                            "<!-- Document local setup and the commands for checks and tests. -->",
                        )
                        .to_string(),
                ),
                "contributing" => (
                    "Contributing",
                    custom
                        .unwrap_or("<!-- Describe how to report issues and contribute changes. -->")
                        .to_string(),
                ),
                "license" if request.options.license != License::None => (
                    "License",
                    format!(
                        "Licensed under {}. See [LICENSE](LICENSE).",
                        request.options.license.id()
                    ),
                ),
                _ => continue,
            };
            if !body.is_empty() {
                blocks.push(format!("## {title}\n\n{body}"));
            }
        }
    }
    Some(format!("{}\n", blocks.join("\n\n")))
}

pub fn render_license(options: &ProjectOptions) -> Option<String> {
    let year = &options.copyright_year;
    let author = options.copyright_name.trim();
    let text = match options.license {
        License::None => return None,
        License::Mit => include_str!("../resources/licenses/MIT.txt")
            .replace("<year>", year)
            .replace("<copyright holders>", author),
        License::Bsd => include_str!("../resources/licenses/BSD-3-Clause.txt")
            .replace("<year>", year)
            .replace("<owner>", author),
        License::Apache => format!(
            "Copyright {year} {author}\n\n{}",
            include_str!("../resources/licenses/Apache-2.0.txt")
        ),
        License::Gpl => format!(
            "Copyright {year} {author}\n\n{}",
            include_str!("../resources/licenses/GPL-3.0-only.txt")
        ),
        License::Unlicense => include_str!("../resources/licenses/Unlicense.txt").to_string(),
    };
    Some(format!("{}\n", text.replace("\r\n", "\n").trim_end()))
}

#[derive(Clone, Debug, Serialize)]
pub struct GeneratedFile {
    pub path: String,
    pub content: String,
}

pub fn generate_files(request: &CreateRequest) -> Result<Vec<GeneratedFile>, AppError> {
    validate_request(request)?;
    let mut files = Vec::new();
    let mut add = |path: &str, content: Option<String>| {
        if let Some(content) = content {
            files.push(GeneratedFile {
                path: path.into(),
                content,
            });
        }
    };
    add("README.md", render_readme(request));
    add(".gitignore", render_gitignore(&request.options));
    add("LICENSE", render_license(&request.options));
    if request.options.editorconfig {
        add(".editorconfig", Some("root = true\n\n[*]\ncharset = utf-8\nend_of_line = lf\ninsert_final_newline = true\ntrim_trailing_whitespace = true\n\n[*.md]\ntrim_trailing_whitespace = false\n".into()));
    }
    if request.options.gitattributes {
        add(".gitattributes", Some("* text=auto\n\n*.png binary\n*.jpg binary\n*.jpeg binary\n*.gif binary\n*.ico binary\n*.pdf binary\n".into()));
    }
    files.extend(crate::ai::generator::generate(request)?);
    crate::ai::generator::validate_files(&files)?;
    Ok(files)
}
